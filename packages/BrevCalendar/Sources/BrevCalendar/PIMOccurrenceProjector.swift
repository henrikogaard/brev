import Foundation

/// One row in the calendar read model (ADR-0089 §1).
///
/// For a projected series row `event` is always the authoritative master
/// record — never a synthesized copy — and `occurrenceIndex` marks the
/// row's position inside the generated series. Non-series and
/// incomplete-series rows carry the record itself with
/// `occurrenceIndex == nil`; their `id` is the record ID.
public struct PIMEventOccurrence: Sendable, Hashable, Identifiable {
    /// Stable view identity: `"\(master.id)|occ|\(startTimestamp)"` for
    /// projected rows; the record ID for raw rows. Never equal to a
    /// provider item key alone and stable across projections and
    /// intervals.
    public let id: String
    /// The authoritative cached record this row displays — the series
    /// master for projected rows.
    public let event: PIMEvent
    /// The occurrence's original boundary inside the series.
    public let originalStart: Date?
    /// The displayed start instant.
    public let start: Date?
    /// The displayed end instant.
    public let end: Date?
    /// 0-based position inside the generated series for projected rows;
    /// nil for raw record rows.
    public let occurrenceIndex: Int?

    /// Whether this row was generated by series projection.
    public var isProjected: Bool { occurrenceIndex != nil }

    public init(
        id: String,
        event: PIMEvent,
        originalStart: Date?,
        start: Date?,
        end: Date?,
        occurrenceIndex: Int?
    ) {
        self.id = id
        self.event = event
        self.originalStart = originalStart
        self.start = start
        self.end = end
        self.occurrenceIndex = occurrenceIndex
    }
}

/// A series whose occurrences could not be fully generated for the
/// requested interval (ADR-0089 §3). The raw master row still renders;
/// the reason explains the gap.
public struct PIMIncompleteSeries: Sendable, Hashable {
    /// The series master record.
    public let event: PIMEvent
    /// Why the series is not fully projected.
    public let reason: PIMRecurrenceUnsupportedReason

    public init(
        event: PIMEvent,
        reason: PIMRecurrenceUnsupportedReason
    ) {
        self.event = event
        self.reason = reason
    }
}

/// The bounded read model for one interval (ADR-0089).
public struct PIMOccurrenceProjection: Sendable, Hashable {
    /// The half-open interval the occurrences were projected for.
    public let interval: DateInterval
    /// Rows sorted by start; undated rows trail last.
    public let occurrences: [PIMEventOccurrence]
    /// Series that rendered as raw master rows instead of generated
    /// occurrences.
    public let incompleteSeries: [PIMIncompleteSeries]

    public init(
        interval: DateInterval,
        occurrences: [PIMEventOccurrence],
        incompleteSeries: [PIMIncompleteSeries]
    ) {
        self.interval = interval
        self.occurrences = occurrences
        self.incompleteSeries = incompleteSeries
    }
}

/// Generates bounded occurrence rows for a date interval (ADR-0089 §3).
///
/// Pure local computation over the cached records: no provider calls,
/// no mutation. Series inside the supported subset project one row per
/// occurrence; everything else degrades to raw master rows plus an
/// explicit incomplete-series entry — never silently truncated output.
public enum PIMOccurrenceProjector {
    /// Largest requestable interval, in days.
    public static let maxIntervalDays = 366
    /// Candidate evaluations allowed per series before coverage is
    /// reported incomplete.
    public static let maxCandidatesPerSeries = 10000

    /// Projects `events` onto `interval`, a half-open date range.
    public static func project(
        _ events: [PIMEvent],
        in interval: DateInterval
    ) -> PIMOccurrenceProjection {
        let exceedsIntervalLimit =
            interval.duration > TimeInterval(maxIntervalDays * 86400)

        let isException: (PIMEvent) -> Bool = {
            $0.recurrenceID != nil || $0.seriesMasterItemKey != nil
        }
        let isCancelledMarker: (PIMEvent) -> Bool = {
            $0.status == .cancelled && isException($0)
        }
        let masters = events.filter {
            ($0.recurrenceDescriptor != nil || $0.recurrenceRule != nil)
                && !isException($0)
        }
        let exceptions = events.filter(isException)

        var rows: [PIMEventOccurrence] = []
        var incomplete: [PIMIncompleteSeries] = []

        for master in masters {
            let linked = exceptions.filter { exception in
                exception.sourceID == master.sourceID
                    && exception.collectionID == master.collectionID
                    && (exception.providerItemKey == master.providerItemKey
                        || exception.seriesMasterItemKey
                        == master.providerItemKey
                        || (exception.uid != nil
                            && exception.uid == master.uid))
            }
            if !linked.isEmpty {
                // Any exception — moved or cancelled — means the master
                // pattern alone no longer describes the series.
                incomplete.append(
                    PIMIncompleteSeries(event: master, reason: .exceptions)
                )
                appendRawRow(master, into: &rows, interval: interval)
                continue
            }
            if exceedsIntervalLimit {
                incomplete.append(
                    PIMIncompleteSeries(
                        event: master,
                        reason: .limitReached
                    )
                )
                appendRawRow(master, into: &rows, interval: interval)
                continue
            }
            switch PIMRecurrenceValidator.validate(master) {
            case .failure(let reason):
                incomplete.append(
                    PIMIncompleteSeries(event: master, reason: reason)
                )
                appendRawRow(master, into: &rows, interval: interval)
            case .success(let rule):
                switch generate(
                    master: master,
                    rule: rule,
                    interval: interval
                ) {
                case .complete(let occurrences):
                    rows.append(contentsOf: occurrences)
                case .exceeded:
                    incomplete.append(
                        PIMIncompleteSeries(
                            event: master,
                            reason: .limitReached
                        )
                    )
                    appendRawRow(master, into: &rows, interval: interval)
                }
            }
        }

        // Non-series records: raw rows. Cancelled exception markers are
        // never output rows — a cancelled instance is invisible rather
        // than strikethrough.
        for event in events where !isCancelledMarker(event) {
            if isException(event) {
                // Exception rows render raw — the projector never
                // substitutes them for generated occurrences.
                appendRawRow(event, into: &rows, interval: interval)
                continue
            }
            guard masters.contains(where: { $0.id == event.id }) == false
            else { continue }
            appendRawRow(event, into: &rows, interval: interval)
        }

        rows.sort { lhs, rhs in
            let left = lhs.start ?? .distantFuture
            let right = rhs.start ?? .distantFuture
            return left != right ? left < right : lhs.id < rhs.id
        }
        return PIMOccurrenceProjection(
            interval: interval,
            occurrences: rows,
            incompleteSeries: incomplete
        )
    }

    // MARK: - Raw rows

    /// Whether the [start, end) interval intersects `interval`
    /// half-open. A zero-length event counts when its point lies inside
    /// the interval, including exactly at `interval.start`.
    private static func overlaps(
        start: Date?,
        end: Date?,
        interval: DateInterval
    ) -> Bool {
        guard let start else { return true } // undated rows always show
        let effectiveEnd = end ?? start
        if effectiveEnd == start {
            return start >= interval.start && start < interval.end
        }
        return start < interval.end && effectiveEnd > interval.start
    }

    private static func appendRawRow(
        _ event: PIMEvent,
        into rows: inout [PIMEventOccurrence],
        interval: DateInterval
    ) {
        guard overlaps(
            start: event.start,
            end: event.end,
            interval: interval
        ) else { return }
        rows.append(
            PIMEventOccurrence(
                id: event.id,
                event: event,
                originalStart: event.start,
                start: event.start,
                end: event.end,
                occurrenceIndex: nil
            )
        )
    }

    // MARK: - Series generation

    private enum GenerationResult {
        case complete([PIMEventOccurrence])
        case exceeded
    }

    private struct Candidate {
        /// Local calendar fields in the generation zone.
        let components: DateComponents
        /// 0-based series position for this slot.
        let index: Int
    }

    /// Generates the overlapping occurrences of a validated series.
    /// A candidate that resolves to a nonexistent/invalid local time is
    /// skipped and does not consume COUNT, but counts toward the
    /// per-series candidate bound.
    private static func generate(
        master: PIMEvent,
        rule: PIMValidatedRecurrence,
        interval: DateInterval
    ) -> GenerationResult {
        guard let masterStart = master.start else {
            return .complete([])
        }
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = rule.timeZone

        var occurrences: [PIMEventOccurrence] = []
        var evaluated = 0
        var emitted = 0
        let initialPeriod = fastForwardStart(
            masterStart: masterStart,
            rule: rule,
            interval: interval,
            calendar: calendar
        )
        var period = initialPeriod
        let days = dayOffsets(
            for: rule,
            masterStart: masterStart,
            calendar: calendar
        )

        while true {
            for (rank, dayOffset) in days.enumerated() {
                guard let components = components(
                    forPeriod: period,
                    dayOffset: dayOffset,
                    masterStart: masterStart,
                    rule: rule,
                    calendar: calendar
                ) else { continue }
                // Every generated slot counts toward the per-series
                // bound — including dates that resolve to nothing.
                evaluated += 1
                guard let start = resolve(
                    components,
                    calendar: calendar
                ) else { continue }
                guard start >= masterStart else { continue }
                if let until = rule.until, start > until {
                    return .complete(occurrences)
                }
                if let count = rule.count, emitted >= count {
                    return .complete(occurrences)
                }
                if start >= interval.end {
                    return .complete(occurrences)
                }
                // The index is the ordinal position: counting emitted
                // occurrences keeps it correct when earlier slots were
                // skipped (weekly BYDAY before DTSTART, invalid monthly
                // dates). Fast-forwarded open-ended series can't
                // recount, so fall back to the slot index — index 0
                // still marks the series start exactly.
                let seriesIndex: Int
                if start == masterStart {
                    seriesIndex = 0
                } else if initialPeriod == 0 {
                    seriesIndex = emitted
                } else {
                    seriesIndex = max(
                        1,
                        emittedIndex(
                            period: period,
                            rank: rank,
                            dayCount: days.count,
                            rule: rule
                        )
                    )
                }
                emitted += 1
                let end = occurrenceEnd(
                    for: master,
                    rule: rule,
                    start: start,
                    calendar: calendar
                )
                if overlaps(
                    start: start,
                    end: end,
                    interval: interval
                ) {
                    occurrences.append(
                        PIMEventOccurrence(
                            id: "\(master.id)|occ|\(Int(start.timeIntervalSince1970))",
                            event: master,
                            originalStart: start,
                            start: start,
                            end: end,
                            occurrenceIndex: seriesIndex
                        )
                    )
                }
            }
            if evaluated > maxCandidatesPerSeries {
                return .exceeded
            }
            period += 1
        }
    }

    /// The first period worth enumerating. COUNT rules must enumerate
    /// from DTSTART so the count is honored; unbounded rules jump to
    /// the period just before the interval instead of evaluating
    /// thousands of dead candidates.
    private static func fastForwardStart(
        masterStart: Date,
        rule: PIMValidatedRecurrence,
        interval: DateInterval,
        calendar: Calendar
    ) -> Int {
        if rule.count != nil { return 0 }
        let span: Int?
        switch rule.frequency {
        case .daily:
            span = calendar.dateComponents(
                [.day],
                from: calendar.startOfDay(for: masterStart),
                to: calendar.startOfDay(for: interval.start)
            ).day
        case .weekly:
            guard let startWeek = weekStart(
                containing: masterStart,
                weekStart: rule.weekStart,
                calendar: calendar
            ),
                let endWeek = weekStart(
                    containing: interval.start,
                    weekStart: rule.weekStart,
                    calendar: calendar
                )
            else { return 0 }
            span = calendar.dateComponents(
                [.day],
                from: startWeek,
                to: endWeek
            ).day.map { $0 / 7 }
        case .monthly:
            let from = calendar.dateComponents(
                [.year, .month],
                from: masterStart
            )
            let to = calendar.dateComponents(
                [.year, .month],
                from: interval.start
            )
            span = ((to.year ?? 0) - (from.year ?? 0)) * 12
                + (to.month ?? 0) - (from.month ?? 0)
        case .yearly:
            span = calendar.dateComponents(
                [.year],
                from: masterStart,
                to: interval.start
            ).year
        }
        guard let span, span > 0 else { return 0 }
        // One period back so occurrences spanning the interval edge
        // are not missed.
        return max(0, span / rule.interval - 1)
    }

    /// Local-day offsets inside one period. DAILY/MONTHLY/YEARLY have
    /// exactly one slot; WEEKLY expands the sorted BYDAY offsets from
    /// WKST (or DTSTART's weekday when BYDAY is absent).
    private static func dayOffsets(
        for rule: PIMValidatedRecurrence,
        masterStart: Date,
        calendar: Calendar
    ) -> [Int] {
        guard rule.frequency == .weekly else { return [0] }
        let wkst = PIMRecurrenceValidator.weekdayIndex(rule.weekStart)
        let days = rule.byDay ?? [
            PIMRecurrenceValidator.weekday(
                for: calendar.component(.weekday, from: masterStart)
            ),
        ]
        return days.map {
            (PIMRecurrenceValidator.weekdayIndex($0) - wkst + 7) % 7
        }.sorted()
    }

    /// The local wall-clock components of one candidate slot.
    /// Computed by component arithmetic — never `date(byAdding:)` month
    /// arithmetic, which clamps days like the 31st.
    private static func components(
        forPeriod period: Int,
        dayOffset: Int,
        masterStart: Date,
        rule: PIMValidatedRecurrence,
        calendar: Calendar
    ) -> DateComponents? {
        let base = calendar.dateComponents(
            [.year, .month, .day, .hour, .minute, .second],
            from: masterStart
        )
        guard let year = base.year, let month = base.month,
              let day = base.day
        else { return nil }
        switch rule.frequency {
        case .daily:
            return shiftedDay(
                year: year, month: month, day: day,
                byDays: period * rule.interval,
                time: base,
                calendar: calendar
            )
        case .weekly:
            // Slots are offsets from the WKST week-start containing
            // DTSTART, not from DTSTART's own weekday.
            guard let weekAnchor = weekStart(
                containing: masterStart,
                weekStart: rule.weekStart,
                calendar: calendar
            ) else { return nil }
            let anchorParts = calendar.dateComponents(
                [.year, .month, .day],
                from: weekAnchor
            )
            return shiftedDay(
                year: anchorParts.year ?? year,
                month: anchorParts.month ?? month,
                day: anchorParts.day ?? day,
                byDays: period * rule.interval * 7 + dayOffset,
                time: base,
                calendar: calendar
            )
        case .monthly:
            let monthIndex = month - 1 + period * rule.interval
            guard monthIndex >= 0 else { return nil }
            return DateComponents(
                year: year + monthIndex / 12,
                month: monthIndex % 12 + 1,
                day: day,
                hour: base.hour,
                minute: base.minute,
                second: base.second
            )
        case .yearly:
            return DateComponents(
                year: year + period * rule.interval,
                month: month,
                day: day,
                hour: base.hour,
                minute: base.minute,
                second: base.second
            )
        }
    }

    /// The local start-of-week (WKST) containing `date` in the
    /// generation zone.
    private static func weekStart(
        containing date: Date,
        weekStart day: ICSParser.Weekday,
        calendar: Calendar
    ) -> Date? {
        let wkst = PIMRecurrenceValidator.weekdayIndex(day)
        let dayStart = calendar.startOfDay(for: date)
        let weekday = calendar.component(.weekday, from: dayStart)
        let offset = (weekday - wkst + 7) % 7
        return calendar.date(byAdding: .day, value: -offset, to: dayStart)
    }

    /// Shifts a local day by whole days without touching the wall
    /// time — DST-safe because the components are taken from a pure
    /// (y/m/d) anchor, then the original h/m/s are reapplied.
    private static func shiftedDay(
        year: Int,
        month: Int,
        day: Int,
        byDays days: Int,
        time base: DateComponents,
        calendar: Calendar
    ) -> DateComponents? {
        guard let anchor = calendar.date(
            from: DateComponents(year: year, month: month, day: day)
        ),
            let shifted = calendar.date(
                byAdding: .day,
                value: days,
                to: anchor
            )
        else { return nil }
        let parts = calendar.dateComponents(
            [.year, .month, .day],
            from: shifted
        )
        return DateComponents(
            year: parts.year,
            month: parts.month,
            day: parts.day,
            hour: base.hour,
            minute: base.minute,
            second: base.second
        )
    }

    /// Resolves local wall-clock components to an instant.
    ///
    /// `nextDate(matchingPolicy: .nextTime, repeatedTimePolicy: .first)`
    /// yields the earlier instant for ambiguous local times. A
    /// nonexistent time (spring-forward gap) or impossible date
    /// (Feb 30, Apr 31, Feb 29 in a common year) resolves to a shifted
    /// instant — or nothing — and the round-trip component check
    /// rejects it, so the slot is skipped without consuming COUNT.
    private static func resolve(
        _ components: DateComponents,
        calendar: Calendar
    ) -> Date? {
        // Day validity first: `date(from:)` normalizes overflow days
        // (Feb 31 → Mar 3), so a mismatch means the slot is invalid.
        let dayComponents = DateComponents(
            year: components.year,
            month: components.month,
            day: components.day
        )
        guard let anchor = calendar.date(from: dayComponents) else {
            return nil
        }
        let anchorParts = calendar.dateComponents(
            [.year, .month, .day],
            from: anchor
        )
        guard anchorParts.year == components.year,
              anchorParts.month == components.month,
              anchorParts.day == components.day
        else { return nil }
        guard let candidate = calendar.nextDate(
            after: anchor.addingTimeInterval(-1),
            matching: components,
            matchingPolicy: .nextTime,
            repeatedTimePolicy: .first,
            direction: .forward
        ) else { return nil }
        let back = calendar.dateComponents(
            [.year, .month, .day, .hour, .minute, .second],
            from: candidate
        )
        guard back.year == components.year,
              back.month == components.month,
              back.day == components.day,
              back.hour == components.hour,
              back.minute == components.minute,
              back.second == components.second
        else { return nil }
        return candidate
    }

    /// The displayed end of one occurrence. Timed events carry the
    /// master's duration in seconds; date-only series reproduce the
    /// stored day span in a GMT calendar so the exclusive end date
    /// stays a whole-day boundary.
    private static func occurrenceEnd(
        for master: PIMEvent,
        rule: PIMValidatedRecurrence,
        start: Date,
        calendar: Calendar
    ) -> Date? {
        guard let masterEnd = master.end else { return nil }
        if rule.startBasis == .dateOnly {
            var gmt = Calendar(identifier: .gregorian)
            gmt.timeZone = TimeZone(identifier: "GMT") ?? .gmt
            let span = gmt.dateComponents(
                [.day],
                from: gmt.startOfDay(for: master.start ?? start),
                to: gmt.startOfDay(for: masterEnd)
            ).day ?? 1
            return start.addingTimeInterval(
                TimeInterval(max(span, 1) * 86400)
            )
        }
        return start.addingTimeInterval(
            masterEnd.timeIntervalSince(master.start ?? start)
        )
    }

    /// Stable series position for a candidate slot. DAILY/MONTHLY/
    /// YEARLY count periods; WEEKLY counts week slots plus the day's
    /// rank inside the week so index 0 marks the series start.
    private static func emittedIndex(
        period: Int,
        rank: Int,
        dayCount: Int,
        rule: PIMValidatedRecurrence
    ) -> Int {
        if rule.frequency == .weekly {
            return period * dayCount + rank
        }
        return period
    }
}
